# -*- coding: utf-8 -*-
"""Разговорные формы просьб: «можешь открыть…», «а запусти-ка…», «пожалуйста».

Хозяин говорит не командами: «Ты можешь где-то через 1,5 часа включить видео»
(07.10.2026). Правила ждали «включи …» и пропускали всё остальное к модели, а
без сети — к отказу. Здесь видно, какие формы правила понимают. Действия — в
песочнице.

    python tests\\probe_casual.py
"""
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from core import config, memory, router

ASKS = [
    "можешь открыть ютуб", "ты можешь открыть телеграм", "а открой-ка стим", "открой пожалуйста блокнот",
    "запусти мне хром пожалуйста", "можешь включить музыку на ютубе", "сделай погромче пожалуйста",
    "можешь сделать потише", "убавь звук", "выключи звук пожалуйста", "останови видео", "поставь видео на паузу",
    "давай следующее видео", "можешь закрыть хром", "будь добр открой загрузки", "мне нужно открыть госуслуги",
    "хочу посмотреть ютуб", "включи музыку", "поставь музыку", "следующий трек", "пауза",
    "можешь напомнить мне завтра в 10 позвонить маме", "напомни пожалуйста через час выпить таблетку",
    "скажи сколько времени", "а который час", "сколько сейчас времени", "какое сегодня число",
    "можешь сказать погоду", "какая там погода", "что там с погодой завтра",
    "сделай скриншот и пришли на телефон", "открой телегу", "зайди в телегу",
    "можешь найти файл отчёт", "найди мне файл резюме", "покажи что у меня в планах",
    "у меня есть дела сегодня", "можешь поставить таймер на 10 минут", "засеки 5 минут",
    "разбуди меня в 7", "выключи комп", "можешь перезагрузить компьютер",
]


def main():
    config.setup_console()
    from tests import sandbox
    acted = sandbox.enable()
    tmp = Path(tempfile.mkdtemp())
    memory.TASKS, memory.FACTS, memory.NOTES_DIR = tmp / "t.json", tmp / "f.json", tmp
    from skills import weather as W
    W.weather = lambda city="", day=0: f"[погода {city} {day}]"
    model = []
    for ask in ASKS:
        acted.clear()
        r = router.handle(router.normalize(ask), config.CFG)
        if r.to_llm:
            model.append(ask)
            print(f"НЕТ → модели  {ask}")
            continue
        did = ", ".join(f"{n}{a[:1]}" for n, a in acted) or ("ждёт «да»" if r.pending else "")
        print(f"ok  правило   {ask} → {did} {r.say[:60]}")
    print(f"\nправилами: {len(ASKS) - len(model)} из {len(ASKS)}")


if __name__ == "__main__":
    main()
