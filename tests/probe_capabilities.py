GIVE_UP = re.compile(r"не могу|не умею|не получилось|не нашёл|не нашел|нет доступа|недоступ|"
                     r"не подключ|не знаю|не поддерж|не удалось", re.I)


def main():
    config.setup_console()
    from tests import sandbox
    acted = sandbox.enable()
    from skills import telegram as TG, tg_desktop as TGD
    TG.open_chat = lambda name: f"[песочница] открыл бы чат «{name}»"
    TG.read_chat = lambda name, n=5: f"[песочница] прочитал бы чат «{name}»"
    tmp = Path(tempfile.mkdtemp())
    memory.TASKS, memory.FACTS, memory.NOTES_DIR = tmp / "t.json", tmp / "f.json", tmp
    use_cloud = "облако" in sys.argv[1:]
    brain = None
    if use_cloud:
        from core.brain import Brain
        brain = Brain(config.CFG)
        tools = []
        brain._run_tool = lambda name, args: (tools.append((name, args)), f"[выполнено: {name}]")[1]

    rules, model, gave_up = 0, [], []
    for ask in ASKS + (HARD if use_cloud else []):
        acted.clear()
        r = router.handle(router.normalize(ask), config.CFG)
        if r.to_llm:
            if not brain:
                model.append(ask)
                print(f"   → модели   {ask}")
                continue
            tools.clear()
            brain.reset()
            answer = brain.ask(ask) or ""
            called = ", ".join(n for n, _ in tools) or "без инструментов"
            bad = not tools and GIVE_UP.search(answer)
            (gave_up if bad else model).append(ask)
            print(f"{'НЕТ' if bad else 'ok '} модель  {ask} → [{called}] {answer[:80]}")
            continue
        said = r.say or ""
        bad = GIVE_UP.search(said) and not acted and not r.pending
        rules += not bad
        if bad:
            gave_up.append(ask)
        mark = "НЕТ" if bad else "ok "
        did = acted[0][0] if acted else ("ждёт «да»" if r.pending else "")
        print(f"{mark} правило {ask} → {did} {said[:80]}")
    print(f"\nправилами: {rules}, модели: {len(model)}, сдался: {len(gave_up)} из {len(ASKS)}")
    for ask in gave_up:
        print(f"   сдался: {ask}")


if __name__ == "__main__":
    main()
