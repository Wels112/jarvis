# -*- coding: utf-8 -*-
"""Узнавание обращения «Джарвис» в распознанном тексте.

Живой тест 13.09.2026 показал, что старый шаблон не работает совсем: из пяти
обращений хозяина не узнано ни одно. «Джарвис» — английское имя, и русский
распознаватель каждый раз подбирает похожие русские слова:

    «Джарви с которой час» · «Джарри Вис, объясни» · «Джаррус, расскажи»
    «Жарится какая погода»

Шаблон был подогнан под синтетический голос и живые варианты не ловил.

Поэтому сравнение идёт по звучанию. Слово упрощается до фонетического скелета:
«дж» и «ж» неразличимы, двойные согласные схлопываются, конечные с/з/ц
сливаются. Первые одно-три слова склеиваются — «Джарри Вис» распалось на два,
но звучит как одно. Скелет сравнивается с «жарвис» по расстоянию редактирования.

Порог выбран так, чтобы ловить «джаррус» (расстояние 2), но не цепляться за
обычные слова вроде «жарить». Искать имя только в начале и в конце фразы —
тоже защита: там обращение и стоит, а посреди «котлеты жарятся» оно не нужно.
"""
import re

# Скелеты живых обращений хозяина, а не одно «правильное» имя. Второй — из показа
# 02.10.2026, где он звал «Джарвицы»: такое обращение не кончается на свистящий,
# и прежнее правило его отвергало вместе с «Джарви» и «Джарвик».
NAMES = ("жарвис", "жарвици")
TARGET = NAMES[0]
MAX_DIST = 1            # сколько правок допускаем к ближайшему из NAMES
# Живые варианты дальше одной правки — только точным совпадением скелета:
# «Джаррус»/«Джарус» (тест 13.09, журнал 07.10.2026) → «жарус». С допуском в одну
# правку к нему прицепилось бы «жару» («жару не люблю»)
EXACT = ("жарус",)


def _skeleton(word: str) -> str:
    w = word.lower().replace("ё", "е")
    w = re.sub(r"[^а-яa-z]", "", w)
    # латиницей распознаватель тоже иногда пишет: jarvis, jarviz
    w = (w.replace("j", "ж").replace("a", "а").replace("r", "р").replace("v", "в")
          .replace("i", "и").replace("s", "с").replace("z", "з").replace("e", "е")
          .replace("o", "о").replace("u", "у").replace("y", "и"))
    w = w.replace("дж", "ж").replace("дз", "з")
    w = re.sub(r"(.)\1+", r"\1", w)                    # джаррус → жарус
    w = re.sub(r"[сзц]$", "с", w)                      # джарвиз → жарвис
    w = w.replace("ы", "и").replace("е", "и") if w.startswith("жар") else w
    return w


def _distance(a: str, b: str) -> int:
    """Расстояние Левенштейна — сколько вставок, удалений и замен между словами."""
    if a == b:
        return 0
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def _name_distance(chunk: str):
    """Насколько кусок похож на имя. None — точно не имя."""
    s = _skeleton(chunk)
    if not s or not s.startswith(("ж", "д")):
        return None
    # Обращение не бывает сильно длиннее или короче самого имени
    if not len(TARGET) - 2 <= len(s) <= len(TARGET) + 2:
        return None
    # Одна правка до любого из живых вариантов. Раньше допускалось две, и чтобы
    # не ловить «жаркий» и «дарвин», требовалось окончание на свистящий — но так
    # отваливались «Джарви» и «Джарвицы», которыми хозяин зовёт его вживую.
    # Один шаг от нескольких вариантов и ловит больше, и промахивается реже:
    # «жаркий», «жарим», «жара», «дарвин» дальше одной правки от всех.
    if s in EXACT:
        return 0
    d = min(_distance(s, name) for name in NAMES)
    return d if d <= MAX_DIST else None


def _best_split(words, from_end: bool):
    """Из склеек в 1–3 слова выбираем самую похожую на имя.

    Первое попавшееся совпадение не годится: «джарри» уже похоже на имя, но
    настоящее обращение — «джарри вис» целиком, и хвост «вис» иначе остался бы
    в команде.
    """
    best = None
    for n in (1, 2, 3):
        if len(words) < n or (from_end and len(words) <= n):
            continue
        chunk = words[-n:] if from_end else words[:n]
        d = _name_distance("".join(chunk))
        if d is None:
            continue
        # меньше правок — лучше; при равенстве берём склейку длиннее
        if best is None or d < best[0] or (d == best[0] and n > best[1]):
            best = (d, n)
    return best


def find(text: str):
    """Ищет обращение в начале или в конце фразы.

    Возвращает (найдено, фраза без обращения).
    """
    words = text.split()
    if not words:
        return False, text

    head = _best_split(words, from_end=False)
    if head:
        return True, " ".join(words[head[1]:]).strip(" ,.!?")

    tail = _best_split(words, from_end=True)          # «открой браузер, джарвис»
    if tail:
        return True, " ".join(words[:-tail[1]]).strip(" ,.!?")

    return False, text


