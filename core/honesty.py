# -*- coding: utf-8 -*-
"""Сторож честности: модель не должна говорить «сделал», если инструмент отказал.

07.10.2026 живая модель дважды сказала хозяину «в телегу продублировал», хотя
инструмент вернул «Telegram не подключён», и «диск почистил», хотя очистка не
запускалась. Закон честности в инструкции она прочла — и всё равно соврала.
Поэтому проверяем сами: в этом ходе инструмент отказал, а в ответе — «сделал»,
«отправил», «готово» без оговорки — значит, просим поправиться.

Общий для живого режима (core/live.py) и обычного мозга (core/brain.py).
"""
import re

# Отказ инструмента: «НЕ ОТПРАВЛЕНО», «не подключён», «Не нашёл…», «ошибка: …»,
# а также ожидание подтверждения — «сделал» до «да» тоже неправда
TOOL_FAILED = re.compile(
    r"^\s*(не |ошибка)|\bне\s+(получ|вышл|удал|смог|принял|наш[её]л|найд|подключ|останов|"
    r"включ|открыл|отправ|сработ|выполн)|недоступ|ТРЕБУЕТСЯ ПОДТВЕРЖДЕНИЕ|вслух не сказал", re.I)
CLAIMED = re.compile(r"\b(отправил|отправлено|продублировал|переслал|скинул|прислал|сделал|"
                     r"сделано|готово|записал|исправил|включил|открыл|нажал|удалил|поставил|"
                     r"добавил|остановил|выключил|закрыл|почистил|очистил|освободил)\w*", re.I)
ADMITTED = re.compile(r"\bне\s+(получ|вышл|удал|смог|отправ|подключ|сдела|наш[её]л|могу|"
                      r"сработ|дош[её]л|ушл)|к сожалению|\bувы\b|не получится", re.I)


# Действие на словах. Без единого вызова инструмента в этом ходе «нажимаю»,
# «открыл», «включаю» — пустые слова: на проверке 07.10.2026 модель на «нажми
# мышкой на YouTube» ответила «Уже нажимаю», ничего не вызвав
ACTION_CLAIM = re.compile(r"\b(нажима|нажал|открыва|открыл|включа|включил|запуска|запустил|"
                          r"отправля|отправил|записал|записыва|поставил|ставлю|выключа|выключил|"
                          r"закрыва|закрыл|удаля|удалил|печата|напечатал|переключ|сохранил|сохраня)\w*",
                          re.I)


def failed(result) -> bool:
    return bool(TOOL_FAILED.search(str(result)))


def unbacked_claim(said: str, tools_called: int) -> str:
    """Что сказать модели, если она заявила действие, не вызвав ни одного инструмента; иначе ''."""
    if tools_called or not said or not ACTION_CLAIM.search(said) or ADMITTED.search(said):
        return ""
    return (f"(Система, не хозяин: ты сказал «{said[:80]}», но не вызвал ни одного инструмента — "
            "значит, ничего не сделано. Если хозяин просит действие — вызови нужный инструмент "
            "сейчас; если такого нет — честно скажи, что этого не умеешь.)")


def false_claim(said: str, failures) -> str:
    """Что сказать модели, если она заявила успех вопреки отказу инструмента; иначе ''."""
    if not (failures and said and CLAIMED.search(said)) or ADMITTED.search(said):
        return ""
    name, result = failures[-1]
    return (f"(Система, не хозяин: инструмент {name} вернул «{result}», а ты сказал хозяину, "
            "что всё получилось. Это неправда. Одной короткой фразой честно поправься.)")
